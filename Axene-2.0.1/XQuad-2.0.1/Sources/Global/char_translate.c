boolean Xc_strcmp_parser(s1, s2)
char	*s1;
char	*s2;
{
 char	c1, c2;
  
 while(*s1 && *s2)
 {
  c1 = Xc_TO_LOWER(*s1);
  c2 = Xc_TO_LOWER(*s2);
      
  if (c1 != c2 && c1 != Xc_SUPPRESS_ACCENT(c2))
   return FALSE;
      
  s1++; s2++;
 }
  
 return (*s1 == *s2);
}









